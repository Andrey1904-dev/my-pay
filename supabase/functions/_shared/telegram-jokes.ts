export function validateJokeRegistry(): void {
  const keys = Object.keys(THRESHOLD_JOKES).map(Number);
  if (keys.length !== 141 || new Set(Object.values(THRESHOLD_JOKES)).size !== 141 ||
      keys.some((key, i) => key !== 500 + i * 25) ||
      Object.values(THRESHOLD_JOKES).some(text => !text.trim()) ||
      new Set([...Object.values(THRESHOLD_JOKES), BELOW_500_JOKE, ABOVE_4000_JOKE]).size !== 143) {
    throw new Error("Incomplete or duplicate Telegram joke registry");
  }
}

export function selectJoke(count: number): string {
  if (!Number.isSafeInteger(count) || count < 0) throw new RangeError("Invalid case count");
  if (count < 500) return BELOW_500_JOKE;
  if (count > 4000) return ABOVE_4000_JOKE;
  return THRESHOLD_JOKES[Math.floor(count / 25) * 25];
}

